#ifndef _flash_h
#define _flash_h
#include <Arduino.h>
//Project classes
#include "globals.h"
#include "lowlevel.h"


#define MAX_WAIT 30                 //Max wait cycles
#define BLOCK_WIDTH 64              //Dump block length
#define MAX_PARTITION_SIZE 0x20000  //Partition size (1/4 FLASH SIZE FOR SST39SF040)

//=============================================================================================
//FLASH FUNCTIONS
//=============================================================================================
class Flash {
private:
  //------------------------------------------------------------------------------
  // FLASH section
  //------------------------------------------------------------------------------
  uint8_t _chip_status = 0xff;  // Chip status 0 empty, 1 programmed,
                                //   2 verified, 4 error, 0xff unknown
  LowLevel _ll;                 // Low level class to read/write on data/address pins
public:
  //---------------------------------------------------------------------------------------------
  // Default constructor
  //---------------------------------------------------------------------------------------------
  Flash(LowLevel ll);

  //=============================================================================================
  // Flash functions
  //=============================================================================================
  //---------------------------------------------------------------------------------------------
  // Reset chip command , return to normal mode
  //---------------------------------------------------------------------------------------------
  void resetChip(void);
  //---------------------------------------------------------------------------------------------
  // Special command to identify chip
  //---------------------------------------------------------------------------------------------
  void identifyChip(uint8_t* brand, uint8_t* model, uint8_t* partitions, uint32_t* size);
  //---------------------------------------------------------------------------------------------
  // Special command to erase entire chip
  //---------------------------------------------------------------------------------------------
  void eraseChip(void);
  //---------------------------------------------------------------------------------------------
  // Program single location (after erasing)
  //---------------------------------------------------------------------------------------------
  void programData(unsigned long address, uint8_t data);
  //---------------------------------------------------------------------------------------------
  // Read single location
  //---------------------------------------------------------------------------------------------
  uint8_t readData(unsigned long address);
  //---------------------------------------------------------------------------------------------
  // Get chip status:  0 empty, 1 programmed, 2 verified, 4 error, 0xff unknown
  //---------------------------------------------------------------------------------------------
  uint8_t getChipStatus(void);
};
#endif  //#define _flash_h