#ifndef _lowlevel_h
#define _lowlevel_h

#include <Arduino.h>
//Fast digital I/O
#include "globals.h"
#include <digitalWriteFast.h>
//---------------------------------------------------------------------------------------------
// Programmer pins section
//---------------------------------------------------------------------------------------------
//51/PB2 = MOSI USED FROM SD CARD !
//50/PB3 = MISO USED FROM SD CARD !

// Address pins
//               00  01  02  03  04  05  06  07  08  09  10  11  12  13  14  15  16  17  18
const int A[] = { 49, 48, 47, 46, 45, 44, 43, 42, 41, 40, 39, 38, 37, 36, 35, 34, 33, 32, 31 };
// Data pins
//               00  01  02  03  04  05  06  07
const int D[] = { 22, 23, 24, 25, 26, 27, 28, 29 };
// Control pins
const int CE = 21;
const int OE = 20;
const int WE = 19;


class LowLevel {
  //private:

public:
  //---------------------------------------------------------------------------------------------
  // init address, data & control pins
  //---------------------------------------------------------------------------------------------
  void init();
  //---------------------------------------------------------------------------------------------
  // set data pins as INPUT/OUTPUT
  // mode = INPUT | OUTPUT
  //---------------------------------------------------------------------------------------------
  void setDataBus(unsigned long mode, bool reset = false);
  //---------------------------------------------------------------------------------------------
  // read data from data pins configured as input
  //---------------------------------------------------------------------------------------------
  uint8_t readData();
  //---------------------------------------------------------------------------------------------
  // write data to data pins configured as output
  //---------------------------------------------------------------------------------------------
  void writeData(uint8_t data);
  //---------------------------------------------------------------------------------------------
  // set address lines
  //---------------------------------------------------------------------------------------------
  void writeAddress(unsigned long address);
  //---------------------------------------------------------------------------------------------
  // highlevel function to read a byte from a given address
  //---------------------------------------------------------------------------------------------
  uint8_t readLocation(unsigned long address);
  //---------------------------------------------------------------------------------------------
  // Send the special address/command combos. The address is written on before WE* falls
  // and the command byte b is written before the WE* rises.
  //---------------------------------------------------------------------------------------------
  void writeLocation(unsigned long address, uint8_t data);
};
#endif  //#define _lowlevel_h